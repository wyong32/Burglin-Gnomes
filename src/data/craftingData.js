function ingredient(item, name, quantity) {
  return { item, name, quantity }
}

function recipe({
  slug,
  name,
  category,
  outputItem = slug,
  priority,
  materials,
  effect,
  bestUse,
  mechanic,
  scenario,
  warning,
  image = itemImage(outputItem),
  areas = [],
  relatedBestiary = [],
  sections = [],
}) {
  return {
    slug,
    name,
    category,
    outputItem,
    priority,
    materials,
    effect,
    bestUse,
    mechanic,
    scenario,
    warning,
    image,
    areas,
    relatedBestiary,
    sections,
  }
}

